"""Streamlit dashboard. All logic lives in the FastAPI backend; this file only
collects input, calls the API through api_client.py and displays results."""
import streamlit as st

import api_client
from api_client import BackendError

CATEGORIES = ["Network", "Email", "Hardware", "Software", "Access", "Other"]
PRIORITIES = ["Low", "Medium", "High", "Critical"]

st.set_page_config(page_title="IT Ticket Resolution Assistant", page_icon="🛠️", layout="wide")

st.markdown(
    """
    <style>
      .block-container {padding-top: 2rem; max-width: 1200px;}
      .step {padding: .65rem .9rem; margin-bottom: .45rem; border-radius: 8px;
             border-left: 4px solid #2563eb; background: rgba(37,99,235,.06);}
      .step b {color: #2563eb; margin-right: .4rem;}
      .badge {display:inline-block; padding:.25rem .7rem; border-radius:999px;
              font-size:.85rem; font-weight:600;}
      .badge-llm {background:#dcfce7; color:#166534;}
      .badge-fb {background:#fef3c7; color:#92400e;}
    </style>
    """,
    unsafe_allow_html=True,
)

st.title("🛠️ IT Ticket Resolution Suggestion Engine")
st.caption(
    "Describe an IT issue. The backend finds similar **resolved** tickets using "
    "TF-IDF + cosine similarity, then an LLM (Groq) turns them into **exactly five** steps. "
    "If the LLM is unavailable, a clearly labelled fallback is used."
)

# ---------------- Sidebar: backend status ----------------
with st.sidebar:
    st.header("System status")
    st.caption(f"Backend: `{api_client.backend_url()}`")
    try:
        health = api_client.get_health()
        st.success("Backend online")
        # .get() with defaults: an older backend version may not send every
        # field, and the sidebar must never crash the whole page.
        total = health.get("historical_tickets", 0)
        resolved = health.get("resolved_tickets")
        c1, c2 = st.columns(2)
        c1.metric("Resolved", resolved if resolved is not None else "?",
                  help="Resolved tickets used for matching")
        c2.metric("All", total, help="Resolved + Open tickets in the database")
        if resolved is None:
            st.warning("Backend is an older version. Restart it from the latest code.")
        if health.get("llm_configured"):
            st.info(f"LLM: Groq `{health.get('llm_model', '?')}`")
        else:
            st.warning("LLM: no GROQ_API_KEY - fallback mode")
        st.caption(f"Similarity threshold: {health.get('similarity_threshold', 0):.2f} | "
                   f"DB: {health.get('database_backend', '?')}")
        if total == 0:
            st.error("Database is empty. Run `python seed_db.py` in the backend folder.")
    except BackendError as exc:
        st.error(str(exc))

tab_suggest, tab_history = st.tabs(["💡 Get suggestions", "📋 Ticket history"])

# ---------------- Tab 1: submit + suggestions ----------------
with tab_suggest:
    with st.form("ticket_form"):
        title = st.text_input("Ticket title", placeholder="e.g. VPN keeps disconnecting")
        description = st.text_area(
            "Description", height=120,
            placeholder="e.g. My VPN drops every few minutes when I work from home.")
        col1, col2, col3 = st.columns([1, 1, 1])
        category = col1.selectbox("Category", CATEGORIES)
        priority = col2.selectbox("Priority", PRIORITIES, index=1)
        save_ticket = col3.checkbox("Also log ticket as Open", value=True)
        submitted = st.form_submit_button("Suggest resolutions", type="primary",
                                          width="stretch")

    if submitted:
        if len(title.strip()) < 3 or len(description.strip()) < 10:
            st.warning("Please enter a title (3+ characters) and a description (10+ characters).")
        else:
            try:
                with st.spinner("Searching historical tickets and generating steps..."):
                    st.session_state["result"] = api_client.suggest(
                        title, description, category, priority, save_ticket)
            except BackendError as exc:
                st.session_state.pop("result", None)
                st.error(str(exc))

    result = st.session_state.get("result")
    if result:
        left, right = st.columns([3, 2], gap="large")
        with left:
            st.subheader("Recommended resolution steps")
            if result["generation_mode"] == "llm":
                st.markdown(f'<span class="badge badge-llm">Generated by Groq LLM · '
                            f'{result["model"]}</span>', unsafe_allow_html=True)
            else:
                st.markdown('<span class="badge badge-fb">Fallback mode · LLM not used</span>',
                            unsafe_allow_html=True)
            st.write("")
            for i, step in enumerate(result["resolution_steps"], start=1):
                safe = step.replace("<", "&lt;").replace(">", "&gt;")
                st.markdown(f'<div class="step"><b>{i}.</b>{safe}</div>', unsafe_allow_html=True)
            for w in result["warnings"]:
                st.warning(w)
            if result["ticket"].get("id"):
                st.caption(f"Ticket logged as #{result['ticket']['id']} (Open).")

        with right:
            st.subheader("Similar historical tickets")
            st.caption("Score = cosine similarity of TF-IDF vectors (0-1). "
                       "It measures word overlap, not probability.")
            if not result["matches"]:
                st.info("No sufficiently similar historical ticket was found.")
            for m in result["matches"]:
                with st.container(border=True):
                    st.markdown(f"**#{m['id']} · {m['title']}**")
                    st.progress(min(m["similarity"], 1.0),
                                text=f"Similarity {m['similarity']:.2f}")
                    st.caption(f"{m['category']} · {m['priority']} priority")
                    with st.expander("Issue and historical resolution"):
                        st.markdown(f"**Issue:** {m['description']}")
                        st.markdown(f"**Resolution:** {m['resolution']}")

# ---------------- Tab 2: ticket history ----------------
with tab_history:
    c1, c2 = st.columns([1, 1])
    status_choice = c1.selectbox("Status", ["All", "Open", "Resolved"])
    page_size = 20
    page = c2.number_input("Page", min_value=1, value=1, step=1)
    try:
        data = api_client.list_tickets(limit=page_size, offset=(page - 1) * page_size,
                                       status=None if status_choice == "All" else status_choice)
        st.caption(f"{data['total']} tickets total")
        if data["items"]:
            st.dataframe(
                [{k: t[k] for k in ("id", "title", "category", "priority", "status", "created_at")}
                 for t in data["items"]],
                width="stretch", hide_index=True)
        else:
            st.info("No tickets on this page.")
    except BackendError as exc:
        st.error(str(exc))
